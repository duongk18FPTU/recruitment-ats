using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using RecruitmentAts.Application.Lookups;
using RecruitmentAts.Application.Positions;
using RecruitmentAts.Application.Users;

namespace RecruitmentAts.Infrastructure.Persistence.Configurations;

internal sealed class PositionConfiguration : IEntityTypeConfiguration<Position>
{
    public void Configure(EntityTypeBuilder<Position> builder)
    {
        builder.ToTable("positions", table =>
        {
            table.HasValues<EmploymentType>("employment_type");
            table.HasValues<PositionLevel>("level");
            table.HasValues<PositionStatus>("status");
            table.HasCheckConstraint("ck_positions_headcount", "headcount >= 1");
        });

        builder.Property(x => x.Id).HasDbDefault("gen_random_uuid()");
        // Generated by the database: JOB-001, JOB-002, ...
        builder.Property(x => x.Code).HasMaxLength(12)
            .HasDefaultValueSql("'JOB-' || lpad(nextval('position_code_seq')::text, 3, '0')");
        builder.Property(x => x.Title).HasMaxLength(150);
        builder.Property(x => x.Location).HasMaxLength(100);
        builder.Property(x => x.EmploymentType).HasMaxLength(20);
        builder.Property(x => x.Level).HasMaxLength(20);
        builder.Property(x => x.Status).HasMaxLength(10).HasDbDefault("'DRAFT'");
        builder.Property(x => x.CriteriaVersion).HasDbDefault("1");
        builder.Property(x => x.CreatedAt).HasDbDefault("now()");
        builder.Property(x => x.UpdatedAt).HasDbDefault("now()");

        builder.HasOne<Department>().WithMany().HasForeignKey(x => x.DepartmentId).OnDelete(DeleteBehavior.NoAction);
        builder.HasOne<User>().WithMany().HasForeignKey(x => x.OwnerId).OnDelete(DeleteBehavior.NoAction);
        builder.HasOne<User>().WithMany().HasForeignKey(x => x.CreatedBy).OnDelete(DeleteBehavior.NoAction);
        builder.HasMany(x => x.Criteria).WithOne().HasForeignKey(x => x.PositionId).OnDelete(DeleteBehavior.Cascade);

        builder.HasIndex(x => x.Code).IsUnique();
        builder.HasIndex(x => new { x.Status, x.DepartmentId }).HasDatabaseName("ix_positions_status");
        builder.HasIndex(x => x.OwnerId).HasDatabaseName("ix_positions_owner");
    }
}
